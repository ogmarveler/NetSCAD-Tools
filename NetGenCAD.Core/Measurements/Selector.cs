        public static double CalculateTextHeight(string fontString, double size)
        {
            if (size <= 0) return 0.0;
            return FontMetricsMap.TryGetValue(fontString, out var m) ? size * m.HeightFactor : size * 1.35;
        }

        public static (double Width, double Height) CalculateTextBounds(string text, string fontString, double size)
            => (CalculateTextWidth(text, fontString, size), CalculateTextHeight(fontString, size));

        /// <summary>
        /// Finds the largest OpenSCAD text size that fits the text within the given max width and/or max height.
        /// Uses binary search for speed and precision.
        /// </summary>
        /// <param name="text">The text string</param>
        /// <param name="fontString">Font string (e.g., "Liberation Serif")</param>
        /// <param name="maxWidth">Maximum allowed width (null = no width constraint)</param>
        /// <param name="maxHeight">Maximum allowed height (null = no height constraint)</param>
        /// <param name="spacing">Text spacing parameter (default 1.0)</param>
        /// <param name="margin">Optional margin/padding to leave around text (applied to both constraints)</param>
        /// <param name="precision">Desired precision in size units (default 0.01)</param>
        /// <param name="maxSize">Upper bound for search (default 100 – increase if needed)</param>
        /// <returns>The largest size that fits, or maxSize if even that is too small</returns>
        public static double CalculateMaxFittingSize(
            string text,
            string fontString,
            double? maxWidth = null,
            double? maxHeight = null,
            double spacing = 1.0,
            double margin = 0.0,
            double precision = 0.01,
            double maxSize = 100.0)
        {
            if (string.IsNullOrEmpty(text)) return maxSize;
            if (!maxWidth.HasValue && !maxHeight.HasValue) return maxSize;

            double low = 0.1;     // Minimum reasonable size
            double high = maxSize;
            double best = low;

            while (high - low > precision)
            {
                double mid = (low + high) / 2.0;
                var (w, h) = CalculateTextBounds(text, fontString, mid, spacing);

                bool fitsWidth = !maxWidth.HasValue || w <= maxWidth.Value - 2 * margin;
                bool fitsHeight = !maxHeight.HasValue || h <= maxHeight.Value - 2 * margin;

                if (fitsWidth && fitsHeight)
                {
                    best = mid;
                    low = mid;
                }
                else
                {
                    high = mid;
                }
            }

            return Math.Round(best, 2); // Round to sensible precision
        }

        /// <summary>
        /// Overload that also supports custom spacing in width calculation
        /// </summary>
        public static (double Width, double Height) CalculateTextBounds(
            string text,
            string fontString,
            double size,
            double spacing = 1.0,
            double fallbackFactor = 0.55)
        {
            double width = CalculateTextWidth(text, fontString, size, spacing, fallbackFactor);
            double height = CalculateTextHeight(fontString, size);
            return (width, height);
        }

        // Updated width calculation with spacing support (exact OpenSCAD behavior)
        public static double CalculateTextWidth(
            string text,
            string fontString,
            double size,
            double spacing = 1.0,
            double fallbackFactor = 0.55)
        {
            if (string.IsNullOrEmpty(text) || size <= 0) return 0.0;

            double naturalSum = 0.0;
            double lastAdvance = fallbackFactor;

            if (PerCharWidthTables.TryGetValue(fontString, out var table))
            {
                foreach (char c in text)
                {
                    double advance = table.TryGetValue(c, out double w) ? w * WidthAdjustment : fallbackFactor;
                    naturalSum += advance;
                }
                if (text.Length > 0)
                    lastAdvance = table.TryGetValue(text[^1], out double w) ? w * WidthAdjustment: fallbackFactor;
            }
            else
            {
                double avg = FontMetricsMap.TryGetValue(fontString, out var m) ? m.AvgWidthFactor * WidthAdjustment : fallbackFactor;
                naturalSum = text.Length * avg;
                lastAdvance = avg;
            }

            // OpenSCAD spacing scales all advances except the last character
            double scaledSum = text.Length <= 1
                ? naturalSum * spacing
                : (naturalSum - lastAdvance) * spacing + lastAdvance;

            return scaledSum * size;
        }
